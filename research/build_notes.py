"""Fill the numbers into research notes, so the figures are pulled straight
from the data instead of being typed (or paraphrased) by hand.

    python research/build_notes.py research/notes/2026-10-19

In each note, everything between <!-- DATA:START --> and <!-- DATA:END -->
is regenerated: today's screen metrics (latest output/screen_*.csv) and the
10+ year history from SEC EDGAR. The written analysis around it is untouched.
"""

from __future__ import annotations

import glob
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ai_desk.fundamentals.edgar import annual_history  # noqa: E402
from company_notes_data import CIKS  # noqa: E402

BLOCK = re.compile(r"<!-- DATA:START -->.*?<!-- DATA:END -->", re.S)


def pct(v, signed=False):
    return "n/a" if pd.isna(v) else (f"{v:+.0%}" if signed else f"{v:.0%}")


def screen_block(row: pd.Series, rank: int, total: int) -> str:
    num = lambda v, f: "n/a" if pd.isna(v) else format(v, f)  # noqa: E731
    return "\n".join([
        f"**Screen rank {rank} of {total}** - overall {row['score']:.0f} "
        f"(quality {row['quality_score']:.0f} · growth {row['growth_score']:.0f} · value {row['value_score']:.0f} · "
        f"strength {row['strength_score']:.0f} · momentum {row['momentum_score']:.0f}; percentiles, 100 = best)",
        "",
        "| market cap | fwd P/E | EV/EBIT | FCF yield | avg ROIC (4y) | revenue growth (3y) | latest qtr y/y | "
        "net debt/EBITDA | share count/yr | 12-1m price |",
        "|---|---|---|---|---|---|---|---|---|---|",
        f"| ${row['market_cap'] / 1e9:,.0f}B | {num(row['forward_pe'], '.1f')} | {num(row['ev_ebit'], '.1f')} | "
        f"{pct(row['fcf_yield'])} | {pct(row['roic_avg'])} | {pct(row['rev_cagr'])} | "
        f"{pct(row['rev_growth_recent'], True)} | {num(row['net_debt_ebitda'], '.1f')}x | "
        f"{pct(row['share_change'], True)} | {pct(row['momentum_12_1'], True)} |",
    ])


def history_block(ticker: str) -> str:
    h = annual_history(CIKS[ticker])
    lines = ["| fiscal year | revenue | growth | gross margin | operating margin | FCF margin | pre-tax ROIC |",
             "|---|---|---|---|---|---|---|"]
    for fy, r in h.iterrows():
        lines.append(f"| {fy} | ${r['revenue_$bn']:.2f}B | {pct(r['revenue_growth'], True)} | "
                     f"{pct(r['gross_margin'])} | {pct(r['operating_margin'])} | {pct(r['fcf_margin'])} | "
                     f"{pct(r['roic_pretax'])} |")
    return "\n".join(lines)


def main(folder: str) -> None:
    screen = pd.read_csv(sorted(glob.glob("output/screen_*.csv"))[-1], index_col=0)
    for note in sorted(Path(folder).glob("*.md")):
        ticker = note.stem
        if ticker not in CIKS:
            continue
        rank = screen.index.get_loc(ticker) + 1
        block = ("<!-- DATA:START -->\n_Numbers below are generated by `research/build_notes.py`._\n\n"
                 "### Today's screen\n\n" + screen_block(screen.loc[ticker], rank, len(screen)) +
                 "\n\n### 10+ years from SEC filings (EDGAR)\n\n" + history_block(ticker) +
                 "\n\nBlank = not tagged in the filing. Pre-tax ROIC = operating income / (assets - cash - "
                 "non-debt current liabilities).\n<!-- DATA:END -->")
        note.write_text(BLOCK.sub(lambda _: block, note.read_text()))
        print(f"filled {note}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "research/notes")
